import { randomBytes } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { openBrowser, sleep } from './cdp.mjs';

const baseUrl=process.env.ASCENTA_WEB_URL||'http://localhost:5175';
const apiUrl=process.env.ASCENTA_API_URL||'http://localhost:4000';
for(const value of [baseUrl,apiUrl])if(!['localhost','127.0.0.1','[::1]'].includes(new URL(value).hostname))throw Error('This test creates local fixtures and only runs against loopback URLs');
const health=await(await fetch(new URL('/api/v1/health',apiUrl))).json();
if(health.data?.dataMode!=='mysql')throw Error('This flow must verify the normal MySQL-backed application');
const output=resolve(process.argv[2]||'docs/evidence/user-flow');
await mkdir(output,{recursive:true});
const runId=Date.now().toString(36)+'-'+randomBytes(3).toString('hex');
const email=`ascenta.browser.${runId}@example.invalid`;
const password='Ascenta!'+randomBytes(18).toString('base64url');
const report={startedAt:new Date().toISOString(),baseUrl,dataMode:health.data.dataMode,testEmail:email,fixturePolicy:'One explicitly identified local test account and journey request; no external email or dispatch.',checks:[],screenshots:[],apiResponses:[],jsErrors:[],consoleErrors:[],success:false};
const browser=await openBrowser();
const assert=(condition,name)=>{report.checks.push({name,passed:!!condition});if(!condition)throw Error(name);console.log(JSON.stringify({check:name,passed:true}));};
browser.listeners.add(({method,params:p})=>{
  if(method==='Runtime.exceptionThrown')report.jsErrors.push(p.exceptionDetails.exception?.description||p.exceptionDetails.text);
  if(method==='Runtime.consoleAPICalled'&&p.type==='error')report.consoleErrors.push(p.args.map(arg=>arg.value||arg.description||arg.type).join(' '));
  if(method==='Network.responseReceived'&&p.response.url.includes('/api/v1/'))report.apiResponses.push({url:p.response.url,status:p.response.status});
});
const go=async path=>{
  await browser.send('Page.navigate',{url:new URL(path,baseUrl).href});
  await browser.waitFor(`document.readyState==='complete' && !!document.querySelector('main') && !!document.querySelector('.site-header')`);
  await browser.waitFor(`Object.keys(document.querySelector('.site-header')).some(key=>key.startsWith('__reactProps'))`);
  await sleep(300);
};
const screenshot=async name=>{
  await browser.evaluate('window.scrollTo(0,0)');await sleep(250);
  await browser.screenshot(join(output,name+'.png'));
  report.screenshots.push(name+'.png');
};
const next=async selector=>{await browser.click('.form-actions button[type="submit"]');await browser.waitFor(`!!document.querySelector(${JSON.stringify(selector)})`);};
try{
  await browser.send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await go('/');await browser.waitFor(`!!document.querySelector('.starter-submit')&&!document.querySelector('.starter-submit').disabled`);
  await browser.click('.starter-submit');
  assert(await browser.evaluate(`location.pathname==='/'&&!document.querySelector('.starter-form').checkValidity()`),'Empty journey fields prevent navigation');
  await browser.fill('#home-pickup','Boston Logan International Airport');
  await browser.fill('#home-destination','Four Seasons Hotel Boston');
  await browser.fill('#home-date',new Date(Date.now()+8*86400000).toISOString().slice(0,10));
  await browser.fill('#home-time','14:30');
  await browser.click('.starter-submit');
  await browser.waitFor(`location.pathname==='/booking'&&document.querySelector('#trip-pickup')?.value==='Boston Logan International Airport'`);
  assert(true,'Home starter transfers its draft to booking');
  await browser.fill('#trip-mode','AIRPORT_TRANSFER');
  await browser.waitFor(`!!document.querySelector('#trip-flight')`);
  await browser.fill('#trip-flight','AA 123');await browser.fill('#trip-luggage','2');await browser.fill('#trip-passengers','2');
  await next('input[name="vehicle-class"]');
  await browser.click('input[name="vehicle-class"][value="EXECUTIVE_SUV"]');
  await next('#passenger-name');
  await browser.fill('#passenger-name','ASCENTA Browser Test');
  await browser.fill('#passenger-phone','+16175550123');
  await browser.fill('#passenger-email',email);
  await browser.fill('#trip-notes','Local migration browser verification '+runId);
  await next('.review-grid');await screenshot('journey-review-before-auth');
  await browser.click('.form-actions button[type="submit"]');
  await browser.waitFor(`location.pathname==='/login'&&!!document.querySelector('#account-email')`);
  assert(await browser.evaluate(`new URLSearchParams(location.search).get('next')==='/booking'`),'Authentication preserves the return route');
  await go('/login?mode=register&next=%2Fbooking');
  await browser.waitFor(`!!document.querySelector('#account-name')`);
  await browser.fill('#account-name','ASCENTA Browser Test');await browser.fill('#account-email',email);await browser.fill('#account-password',password);
  await browser.click('.auth-card .check-field input[type="checkbox"]');
  await browser.click('.auth-card button[type="submit"]');
  await browser.waitFor(`!!document.querySelector('.auth-card .alert button')`);
  assert(await browser.evaluate(`document.body.innerText.includes('no email was sent')`),'Registration explicitly uses local verification without sending email');
  assert(report.apiResponses.some(item=>item.url.endsWith('/auth/register')&&item.status===202),'Express creates the local account');
  await browser.click('.auth-card .alert button');
  await browser.waitFor(`document.querySelector('#account-token')?.value.length>=32`);
  assert(await browser.evaluate(`(()=>{const token=document.querySelector('#account-token').value;return ![...Object.values(sessionStorage),...Object.values(localStorage)].some(value=>value.includes(token))})()`),'Verification token is absent from browser storage');
  await browser.click('.auth-card button[type="submit"]');
  await browser.waitFor(`!!document.querySelector('.auth-card .alert-success')&&!document.querySelector('#account-token')`);
  assert(report.apiResponses.some(item=>item.url.endsWith('/auth/verify-email')&&item.status===200),'Account email verification succeeds');
  await screenshot('email-verified');
  await browser.click('.auth-card .auth-footnote button');await browser.waitFor(`!!document.querySelector('#account-email')`);
  await browser.fill('#account-email',email);await browser.fill('#account-password',password);await browser.click('.auth-card button[type="submit"]');
  await browser.waitFor(`location.pathname==='/booking'&&!!document.querySelector('#trip-pickup')`);
  assert(await browser.evaluate(`document.querySelector('#trip-pickup').value==='Boston Logan International Airport'&&document.querySelector('#trip-flight').value==='AA 123'`),'Journey and flight draft survive registration, verification, and sign-in');
  await next('input[name="vehicle-class"]');
  assert(await browser.evaluate(`document.querySelector('input[name="vehicle-class"]:checked')?.value==='EXECUTIVE_SUV'`),'Vehicle preference survives authentication');
  await next('#passenger-name');
  assert(await browser.evaluate(`document.querySelector('#trip-notes').value===${JSON.stringify('Local migration browser verification '+runId)}`),'Passenger notes survive authentication');
  await next('.review-grid');
  await browser.click('.form-panel .check-field input[type="checkbox"]');
  await browser.click('.form-actions button[type="submit"]');
  await browser.waitFor(`!!document.querySelector('.booking-success .success-reference strong')`);
  report.reference=await browser.evaluate(`document.querySelector('.success-reference strong').innerText.trim()`);
  assert(!!report.reference,'MySQL-backed API returns a journey request reference');
  assert(report.apiResponses.some(item=>/\/(reservations|requests)$/.test(item.url)&&item.status===201),'Journey creation succeeds through Express');
  await screenshot('journey-saved');
  await browser.click('.success-actions a[href="/dashboard"]');
  const ownCard=`[...document.querySelectorAll('.request-reference')].some(el=>el.innerText.trim()===${JSON.stringify(report.reference)})`;
  await browser.waitFor(`location.pathname==='/dashboard'&&${ownCard}`);
  await browser.evaluate(`document.querySelectorAll('.request-card').forEach(card=>{if(card.querySelector('.request-reference')?.innerText.trim()===${JSON.stringify(report.reference)})card.dataset.browserCheck='created'})`);
  await browser.click('[data-browser-check="created"] .request-actions button');
  assert(await browser.evaluate(`document.querySelector('[data-browser-check="created"]').innerText.includes(${JSON.stringify(runId)})&&document.querySelector('[data-browser-check="created"]').innerText.includes('AA 123')`),'Dashboard retains notes and flight details');
  await screenshot('dashboard-desktop');
  await browser.send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});await screenshot('dashboard-mobile');
  assert(await browser.evaluate(`document.documentElement.scrollWidth<=innerWidth+1`),'Authenticated mobile dashboard has no horizontal overflow');
  await browser.evaluate(`window.__ascentaBrowserReload=${JSON.stringify(runId)}`);await browser.send('Page.reload');
  await browser.waitFor(`window.__ascentaBrowserReload===undefined&&${ownCard}`);
  assert(true,'Authenticated session and journey survive a full document reload');
  await browser.send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await go('/account');await browser.waitFor(`document.querySelector('#profile-email')?.value===${JSON.stringify(email)}`);await screenshot('account');
  await browser.click('.signout');await browser.waitFor(`location.pathname==='/'&&document.querySelector('.sign-in-link')?.getAttribute('href')==='/login'`);
  await browser.waitFor(`document.readyState==='complete'`);await sleep(350);
  const status=await browser.evaluate(`fetch(${JSON.stringify(new URL('/api/v1/auth/me',apiUrl).href)},{credentials:'include'}).then(response=>response.status)`);
  assert(status===401,'Logout revokes the server session');
  await go('/dashboard');await browser.waitFor(`document.body.innerText.includes('Your personal space awaits.')`);
  assert(await browser.evaluate(`!document.querySelector('.request-card')`),'Signed-out dashboard hides account requests');
  assert(report.jsErrors.length===0,'No JavaScript exceptions in the complete account and booking flow');
  assert(report.consoleErrors.length===0,'No application console errors in the complete flow');
  report.success=true;
}catch(error){
  report.error=error.message;process.exitCode=1;
  const containsToken=await browser.evaluate(`!!document.querySelector('#account-token')`).catch(()=>true);
  if(!containsToken)await browser.screenshot(join(output,'failure.png')).catch(()=>{});
  else report.failureScreenshotOmitted='Verification fields may contain a one-time token.';
  console.error(error.message);
}
finally{
  report.finishedAt=new Date().toISOString();await writeFile(join(output,'report.json'),JSON.stringify(report,null,2));await browser.close();
  console.log(JSON.stringify({success:report.success,checks:report.checks.length,reference:report.reference,temporaryLoginFile:report.temporaryLoginFile,report:join(output,'report.json')}));
}
